    head("3. หลักฐานการเสนอราคา")
    _p(doc, "ผู้เสนอราคาจะต้องเสนอเอกสารหลักฐานยื่นมาพร้อมกับซองใบเสนอราคา "
            "โดยแยกไว้นอกซองใบเสนอราคาเป็น 2 ส่วน คือ", align="justify", indent=1.25, after=2)
    _p(doc, "3.1 ส่วนที่ 1 อย่างน้อยต้องมีเอกสารดังต่อไปนี้", bold=True, indent=1.25, after=1)
