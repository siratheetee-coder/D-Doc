def _money(v) -> str:
    return f"{float(v or 0):,.2f}"


def _lines(text, fallback=()):
    out = [ln.strip().lstrip("-").strip() for ln in (text or "").splitlines() if ln.strip()]
    return out or list(fallback)


def _class_table(doc, level, items):
    """ตารางรายละเอียดคุณลักษณะเฉพาะของชั้นหนึ่ง ๆ -> คืนยอดรวมของชั้น"""
    _p(doc, f"รายละเอียดคุณลักษณะเฉพาะ รายการหนังสือเรียน ชั้น{level}",
       bold=True, indent=0.6, before=6, after=2)
    headers = ["ที่", "รายการหนังสือ", "ราคา", "จำนวน", "เป็นเงิน"]
    widths = [Cm(1.0), Cm(8.2), Cm(2.0), Cm(2.0), Cm(2.6)]
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    _fixed_cols(t, widths)
    _repeat_header_row(t.rows[0]); _no_split_row(t.rows[0])
    for c, h, w in zip(t.rows[0].cells, headers, widths):
        _set_cell(c, h, bold=True, align="center", size=14)
        c.width = w
    total = 0.0
    for i, it in enumerate(items, start=1):
        amount = float(it["price"]) * float(it["qty"])
        total += amount
        title = it["title"]
        if it.get("publisher"):
            title += "\nสำนักพิมพ์/ผู้จัดพิมพ์ " + it["publisher"]
        vals = [str(i), title, _money(it["price"]), f"{it['qty']:g}", _money(amount)]
        r = t.add_row(); _no_split_row(r)
        for c, v, w, al in zip(r.cells, vals, widths,
                               ["center", "left", "right", "center", "right"]):
            _set_cell(c, v, align=al, size=14)
            c.width = w
    r = t.add_row(); _no_split_row(r)
    _set_cell(r.cells[1], "รวม", bold=True, align="right", size=14)
    _set_cell(r.cells[4], _money(total), bold=True, align="right", size=14)
    for c, w in zip(r.cells, widths):
        c.width = w
    return total


def render_book_tor(school, tp, groups) -> str:
    """tp = TextbookPurchase · groups = [(level, [{title, price, qty}]), ...] เรียงตามชั้น

    โครงสร้างตามไฟล์ "ขอบเขตของงานซื้อหนังสือ" ที่โรงเรียนใช้จริง (8 หัวข้อ)
    """
    doc = Document(); set_a4(doc)
    _font(doc)
    sname = (school.name or "โรงเรียน").strip()
    n_items = sum(len(items) for _, items in groups)
    fy = tp.fiscal_year or tp.year
    grand = sum(float(it["price"]) * float(it["qty"]) for _, items in groups for it in items)
    budget = float(tp.total_budget or 0) or grand
    ref = float(tp.price_ref or 0) or grand
    area = (getattr(school, "area_office", "") or "").strip()
    delivery_place = (tp.delivery_place or "").strip() or sname

    def head(text):
        _p(doc, text, bold=True, before=6, after=2)

    def item(text, *, no="", ind=1.25):
        _p(doc, (f"{no} {text}" if no else text), align="justify", indent=ind, after=1)

    _p(doc, "ขอบเขตของงาน (Terms of Reference : TOR)", align="center", bold=True, size=18, after=0)
    _p(doc, f"การจัดซื้อหนังสือเรียน จำนวน {n_items} รายการ "
            f"({tp.budget_source or 'งบอุดหนุนรัฐบาล'})", align="center", bold=True, size=16, after=0)
    _p(doc, f"ประจำปีงบประมาณ พ.ศ. {fy}", align="center", bold=True, size=16, after=0)
    _p(doc, "--------------------------------", align="center", after=6)

    # ------------------------------------------------ 1. ข้อมูลเกี่ยวกับโครงการ
    head("1. ข้อมูลเกี่ยวกับโครงการ")
    _p(doc, "ความเป็นมา", bold=True, indent=1.25, after=1)
    _p(doc, sname + (f" {area}" if area else ""), align="justify", indent=1.25, after=0)
    _p(doc, f"มีความประสงค์ที่จะซื้อหนังสือเรียน จำนวน {n_items} รายการ "
            f"ด้วยวิธี{tp.method or 'เฉพาะเจาะจง'} ได้รับจัดสรรงบประมาณรายจ่าย "
            f"ประจำปี พ.ศ. {fy} งบ{tp.budget_source or 'เงินอุดหนุนรัฐบาล'} "
            "โครงการสนับสนุนค่าใช้จ่ายในการจัดการศึกษาตั้งแต่ระดับอนุบาลจนจบการศึกษาขั้นพื้นฐาน "
            "เงินอุดหนุนทั่วไป รายการค่าหนังสือเรียน ตามที่ได้จัดสรรงบประมาณ",
       align="justify", after=2)
    _p(doc, f"ชื่อโครงการ  จัดซื้อหนังสือเรียน ปีการศึกษา {tp.year} "
            f"โดยวิธี{tp.method or 'เฉพาะเจาะจง'}", indent=1.25, after=1)
    _p(doc, f"เงินงบประมาณโครงการ  จำนวน {_money(budget)} บาท ({bahttext(budget)})",
       indent=1.25, after=1)
    _p(doc, f"ราคากลาง  เป็นเงิน {_money(ref)} บาท ({bahttext(ref)})", indent=1.25, after=2)

    # ------------------------------------------------ 2. คุณสมบัติของผู้เสนอราคา
    head("2. คุณสมบัติของผู้เสนอราคา")
