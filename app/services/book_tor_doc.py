    head("5. ขอบเขตของงาน / แบบรูปรายการ / คุณลักษณะเฉพาะ")
    _p(doc, f"รายละเอียดตามเอกสารแนบท้าย จำนวน {n_items} รายการ "
            f"รวมเป็นเงิน {_money(grand)} บาท ({bahttext(grand)})",
       align="justify", indent=1.25, after=2)

    # ------------------------------------------------ 6. ระยะเวลาดำเนินการ
    head("6. ระยะเวลาดำเนินการ")
