def items_for(level, domain):
    """ตัวบ่งชี้ของชั้นนี้ในด้านนี้ · ชั้นที่ไม่ใช่อนุบาลคืนลิสต์ว่าง"""
    return INDICATORS.get((level or "").strip(), {}).get(domain, [])


def is_kinder(level) -> bool:
    """ชั้นนี้เป็นระดับปฐมวัยไหม"""
    return (level or "").strip() in KINDER_LEVELS


def code_of(domain, seq) -> str:
    """คีย์ที่ใช้เก็บผลรายข้อในฐานข้อมูล เช่น phys:3"""
    return f"{domain}:{seq}"


def domain_average(values) -> int:
    """สรุประดับคุณภาพรายด้านจากผลรายข้อ (ปัดเข้าใกล้สุด · ไม่มีข้อมูล = 0)"""
    vals = [v for v in values if v]
    if not vals:
        return 0
    avg = sum(vals) / len(vals)
    return 3 if avg >= 2.5 else 2 if avg >= 1.5 else 1
