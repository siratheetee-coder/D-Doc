def walk(answers: list) -> dict:
    """เดินต้นไม้ตามคำตอบ (ใช้ในเทสต์และตรวจฝั่งเซิร์ฟเวอร์)

    answers = ลำดับคำตอบ: ตัวเลือก = index (int) · วงเงิน = จำนวนเงิน (float)
    คืน {"node": id ถัดไป} ถ้ายังไม่จบ หรือ {"result": key, "set": {...}} ถ้าจบแล้ว
    """
    node_id, carried = "start", {}
    for ans in answers:
        node = NODES[node_id]
        if node["kind"] == "amount":
            amount = float(ans)
            carried["amount"] = amount
            step = next(r for r in node["ranges"] if r["max"] is None or amount <= r["max"])
        else:
            step = node["options"][int(ans)]
        carried.update(step.get("set", {}))
        if "result" in step:
            return {"result": step["result"], "set": carried}
        node_id = step["next"]
    return {"node": node_id, "set": carried}


