"""ชื่อหน่วยงานและตำแหน่งผู้บริหาร ใช้ร่วมกันทุกเอกสาร

เดิมแต่ละไฟล์เขียนกติกาเองว่า "ถ้าชื่อขึ้นต้นด้วยโรงเรียน ให้ใช้ ผู้อำนวยการ + ชื่อ
ถ้าไม่ใช่ ให้ใช้ ผู้อำนวยการโรงเรียน" กระจายอยู่เกือบยี่สิบจุด ผลคือ
  - หน่วยงานอื่นที่ไม่ใช่โรงเรียน กรอกตำแหน่งไว้แล้วก็ยังโดนทับด้วย "ผู้อำนวยการโรงเรียน"
  - โรงเรียนที่ชื่อไม่ได้ขึ้นต้นด้วยคำว่าโรงเรียน (เช่น "อนุบาลขอนแก่น")
    ได้ "ผู้อำนวยการโรงเรียน" ลอย ๆ ไม่มีชื่อโรงเรียนต่อท้าย
"""

DEFAULT_HEAD = "ผู้อำนวยการโรงเรียน"
# คำลงท้ายตำแหน่งที่หมายถึง "หน่วยงาน" กลาง ๆ ยังไม่เจาะจงว่าหน่วยไหน
_GENERIC_TAILS = ("โรงเรียน", "สถานศึกษา")


def org_name(school) -> str:
    return (getattr(school, "name", "") or "").strip()


def head_title(school) -> str:
    """ตำแหน่งผู้บริหารแบบเต็ม เช่น 'ผู้อำนวยการโรงเรียนบ้านหินลาด'

    กติกา
      1. ตำแหน่งที่ตั้งไว้เป็นหลักเสมอ ไม่เดาจากชื่อหน่วยงาน
      2. ตำแหน่งที่ยังกลาง ๆ (ลงท้ายด้วยโรงเรียน/สถานศึกษา) ให้ต่อชื่อหน่วยงานให้
      3. ตำแหน่งที่เจาะจงอยู่แล้ว (เช่น นายกเทศมนตรีตำบลหินลาด) ใช้ตามนั้น ไม่ต่ออะไร
    """
    pos = (getattr(school, "director_position", "") or "").strip() or DEFAULT_HEAD
    name = org_name(school)
    if not name or name in pos:
        return pos
    for tail in _GENERIC_TAILS:
        if pos.endswith(tail):
            # ชื่อหน่วยงานขึ้นต้นด้วยคำเดียวกันอยู่แล้ว ไม่ต้องเขียนซ้ำ
            return (pos[: -len(tail)] + name) if name.startswith(tail) else (pos + name)
    return pos


def org_display(school) -> str:
    """ชื่อหน่วยงานสำหรับหัวกระดาษ เติมคำว่า 'โรงเรียน' ให้เฉพาะหน่วยงานที่เป็นโรงเรียน

    ของเดิมเติมให้ทุกกรณี หน่วยงานอื่นจึงกลายเป็น 'โรงเรียนเทศบาลตำบลหินลาด'
    ดูจากตำแหน่งผู้บริหารที่ตั้งไว้ว่ายังเป็นของโรงเรียนอยู่ไหม
    """
    name = org_name(school)
    pos = (getattr(school, "director_position", "") or "").strip() or DEFAULT_HEAD
    is_school = pos.endswith("โรงเรียน")
    if not name:
        return "โรงเรียน" if is_school else ""
    if is_school and not name.startswith("โรงเรียน"):
        return "โรงเรียน" + name
    return name


def head_title_short(school) -> str:
    """ตำแหน่งสั้น ไม่มีชื่อหน่วยงาน สำหรับบรรทัดใต้ลายเซ็นที่มีชื่อหน่วยงานอยู่แล้ว"""
    return (getattr(school, "director_position", "") or "").strip() or DEFAULT_HEAD


def parent_office(school, blank: str = "") -> str:
    """ต้นสังกัดที่ต้องส่งรายงานให้ (ตั้งค่าได้ที่หน้าตั้งค่า)

    ของเดิมถ้าไม่ได้กรอกจะเติมคำว่า "สำนักงานเขตพื้นที่การศึกษา" ให้เอง
    ซึ่งผิดสำหรับหน่วยงานที่ไม่ใช่โรงเรียน · เว้นเป็นช่องว่างให้เติมมือแทน
    """
    return (getattr(school, "area_office", "") or "").strip() or blank
