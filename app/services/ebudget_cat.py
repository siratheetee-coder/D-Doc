def guess_expense(note: str = "", item_name: str = "", project: str = "") -> str:
    """เดาหมวดรายจ่ายจากข้อความที่ครูพิมพ์ · เดาไม่ได้ = '' (ให้ครูเลือกเอง)

    ลำดับการดู: ข้อความรายการ -> ชื่อหมวดงบ -> ชื่อโครงการ
    ถ้าผูกโครงการไว้แต่ไม่เข้าเงื่อนไขอื่น ให้เป็น "โครงการตามแผนปฏิบัติการ" ของด้านวิชาการ
    """
    for text in (note, item_name, project):
        t = (text or "").strip()
        if not t:
            continue
        for words, code in _GUESS:
            if any(w in t for w in words):
                return code
    return "1.1" if (project or "").strip() else ""


# ช่องในส่วนที่ 2 (ประเภทเงิน) -> ข้อย่อยในส่วนที่ 3 ที่ปกติเงินประเภทนั้นมาจาก
_SLOT_TO_INCOME = {
    **{f"3.1.{n}": f"i2.1.{n}" for n in range(1, 8)},
    "3.2.1": "i4.1", "3.2.2": "i4.2", "3.2.3": "i2.2.1", "3.2.4": "i2.2.2", "3.2.5": "i2.2.2",
    "3.3": "i5.1", "3.4": "i5.2", "3.5": "i5.3", "3.6": "i5.4", "3.7": "i5.5", "3.8": "i5.6",
    "3.9": "i5.7", "3.10": "i5.8", "3.11": "i5.9", "3.12": "i3.3", "3.13": "i5.10",
    "2.1": "i6.1", "2.2": "i6.2", "2.3": "i6.3", "2.4": "i6.4", "2.5": "i6.5",
}


def guess_income(account_name: str = "", item_name: str = "", note: str = "", slot: str = "") -> str:
    """เดาข้อย่อยส่วนที่ 3 · ดูประเภทเงินของบัญชี/หมวดก่อน (แม่นกว่า) แล้วค่อยดูข้อความ"""
    text = " ".join(x or "" for x in (note, item_name, account_name))
    local = any(w in text for w in ("อปท", "เทศบาล", "อบต", "อบจ", "ท้องถิ่น"))
    if slot in _SLOT_TO_INCOME and not (local and slot.startswith("3.1.")):
        return _SLOT_TO_INCOME[slot]
    if "อาหารกลางวัน" in text:
        return "i4.2"
    if local:
        return "i4.3"
    if any(w in text for w in ("เสมอภาค", "กสศ")):
        return "i3.3"
    if "ดอกเบี้ย" in text:
        return "i6.4"
    for n, word in enumerate(("รายหัว", "หนังสือเรียน", "อุปกรณ์การเรียน", "เครื่องแบบ",
                              "กิจกรรมพัฒนา", "ยากจน", "พักนอน"), 1):
        if word in text:
            return f"i2.1.{n}"
    if "จัดการเรียนการสอน" in text:
        return "i2.1.1"
    if "บริจาค" in text:
        return "i5.2"
    if "บำรุงการศึกษา" in text:
        return "i5.1"
    return "i5.3" if "รายได้" in text else ""


def guess(txn, item_name: str = "", project: str = "", account_name: str = "", slot: str = "") -> str:
    """เดาหมวดให้รายการหนึ่ง (เลือกชุดตามรับหรือจ่าย)"""
    if (getattr(txn, "kind", "in") or "in") == "out":
        return guess_expense(getattr(txn, "note", ""), item_name, project)
    return guess_income(account_name, item_name, getattr(txn, "note", ""), slot)
