def _income_full_label(code: str) -> str:
    """ป้ายเต็มของข้อย่อย เช่น i2.1.1 -> "2.1 (1) รายหัว" (ข้อ (n) ซ้ำกันหลายข้อ ต้องบอกข้อแม่ด้วย)"""
    label = dict((c, l) for c, l, _v in INCOME_TREE)
    parts = code[1:].split(".")
    if len(parts) <= 2:
        return label[code]
    parent = "i" + ".".join(parts[:2])
    mid = ""
    if len(parts) == 4:
        mid = " " + label["i" + ".".join(parts[:3])].split(" ", 1)[0]
    return f"{parent[1:]}{mid} {label[code]}"


