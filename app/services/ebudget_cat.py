def guess_expense(note: str = "", item_name: str = "", project: str = "") -> str:
    """เดาหมวดรายจ่ายจากข้อความที่ครูพิมพ์ · เดาไม่ได้ = '' (ให้ครูเลือกเอง)

    ลำดับการดู: ข้อความรายการ -> ชื่อหมวดงบ -> ชื่อโครงการ
    ถ้าผูกโครงการไว้แต่ไม่เข้าเงื่อนไขอื่น ให้เป็น "โครงการตามแผนปฏิบัติการ" ของด้านวิชาการ
    """
    for text in (note, item_name, project):
        t = (text or "").strip()
        if not t:
            continue
        for words, code in _GUESS:
            if any(w in t for w in words):
                return code
    return "1.1" if (project or "").strip() else ""


def guess_income(account_name: str = "", item_name: str = "", note: str = "") -> str:
    """เดาแหล่งที่มาของเงินรับ"""
    text = " ".join(x or "" for x in (note, item_name, account_name))
    if any(w in text for w in ("อปท", "เทศบาล", "อบต", "อบจ", "ท้องถิ่น", "อาหารกลางวัน")):
        return "i4"
    if any(w in text for w in ("เสมอภาค", "กสศ", "จังหวัด")):
        return "i3"
    if any(w in text for w in ("ดอกเบี้ย", "ส่งคืน")):
        return "i6"
    if any(w in text for w in ("อุดหนุน", "รายหัว", "จัดการเรียนการสอน", "หนังสือเรียน",
                               "อุปกรณ์การเรียน", "เครื่องแบบ", "กิจกรรมพัฒนา", "ยากจน")):
        return "i2"
    return "i5"


def guess(txn, item_name: str = "", project: str = "", account_name: str = "") -> str:
    """เดาหมวดให้รายการหนึ่ง (เลือกชุดตามรับหรือจ่าย)"""
    if (getattr(txn, "kind", "in") or "in") == "out":
        return guess_expense(getattr(txn, "note", ""), item_name, project)
    return guess_income(account_name, item_name, getattr(txn, "note", ""))
